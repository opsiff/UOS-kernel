#!/bin/sh
# SPDX-License-Identifier: GPL-2.0
#
# Generate sort_rs.rs, the user-space copy of the Rust heapsort, from the tree
# sources. They cannot be used directly: they refer to the kernel crate
# (crate::bindings) and to kernel::sort, while this copy is a standalone
# user-space object.
#
# Transitional: goes away with the C half of lib/sort.c.

set -e

top=$(git rev-parse --show-toplevel 2>/dev/null || echo ../../../../..)
impl=$top/rust/kernel/algo/sort.rs
facade=$top/rust/kernel/sort.rs

for f in "$impl" "$facade"; do
	[ -r "$f" ] || { echo "$f: not found" >&2; exit 1; }
done

{
	echo '// SPDX-License-Identifier: GPL-2.0'
	echo '//'
	echo '// GENERATED by mk-sort-rs.sh from rust/kernel/algo/sort.rs and'
	echo '// rust/kernel/sort.rs. Do not edit; rerun the script instead.'
	echo
	# The implementation. Drop its own SPDX line and module docs, and replace
	# the kernel-crate import with the out-of-line __cond_resched() that
	# cond_resched() would call inside the kernel.
	sed -e '0,/^\/\/ SPDX-License-Identifier/{/^\/\/ SPDX-License-Identifier/d}' \
	    -e '/^\/\/!/d' "$impl" | \
	sed -e 's|^use crate::bindings;$|mod bindings {\n    extern "C" {\n        #[link_name = "__cond_resched"]\n        pub fn cond_resched() -> core::ffi::c_int;\n    }\n}|'
	echo
	# The C ABI facade. Same file scope now, so drop its SPDX line, module
	# docs, the import that pulled the implementation in, and the imports and
	# type aliases the implementation already provides.
	sed -e '0,/^\/\/ SPDX-License-Identifier/{/^\/\/ SPDX-License-Identifier/d}' \
	    -e '/^\/\/!/d' \
	    -e '/^use crate::algo::sort::{$/,/^};$/d' \
	    -e '/^use core::ffi::{c_int, c_void};$/d' \
	    -e '/^\/\/\/ cmp_func_t, see include\/linux\/sort.h.$/d' \
	    -e '/^type CmpFunc = /d' \
	    -e '/^\/\/\/ swap_func_t, see include\/linux\/sort.h.$/d' \
	    -e '/^type SwapFunc = /d' "$facade"
} > sort_rs.rs
