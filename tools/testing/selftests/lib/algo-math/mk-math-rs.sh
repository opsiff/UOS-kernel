#!/bin/sh
# SPDX-License-Identifier: GPL-2.0
#
# Generate math_rs.rs, the user-space copy of the Rust int_sqrt()/lcm(), from
# the tree sources. They cannot be used unmodified: lcm.rs refers to
# crate::algo::gcd, which inside the kernel is a wrapper over C's gcd().
# Here that same C gcd() is the reference implementation from math_c_orig.c, so
# the composition under test matches the kernel exactly.
#
# Transitional: goes away with the C halves of lib/math/{lcm,int_sqrt}.c.

set -e

top=$(git rev-parse --show-toplevel 2>/dev/null || echo ../../../../../..)
gcd_rs=$top/rust/kernel/algo/gcd.rs
isqrt=$top/rust/kernel/algo/int_sqrt.rs
lcm=$top/rust/kernel/algo/lcm.rs

for f in "$gcd_rs" "$isqrt" "$lcm"; do
	[ -r "$f" ] || { echo "$f: not found" >&2; exit 1; }
done

{
	tag='SPDX-'
	tag="${tag}License-Identifier: GPL-2.0"
	printf '// %s\n' "$tag"
	echo '//'
	echo '// GENERATED by mk-math-rs.sh from rust/kernel/algo/int_sqrt.rs and'
	echo '// rust/kernel/algo/lcm.rs. Do not edit; rerun the script instead.'
	echo
	echo '#![allow(dead_code)]'
	echo
	echo 'pub mod algo {'
	echo '    pub mod gcd {'
	sed -e '0,/^\/\/ SPDX-License-Identifier/{/^\/\/ SPDX-License-Identifier/d}' \
	    -e '/^\/\/!/d' "$gcd_rs"
	echo '    }'
	echo
	echo '    pub mod int_sqrt {'
	# Drop the SPDX line and the module docs; keep everything else verbatim.
	sed -e '0,/^\/\/ SPDX-License-Identifier/{/^\/\/ SPDX-License-Identifier/d}' \
	    -e '/^\/\/!/d' "$isqrt"
	echo '    }'
	echo
	echo '    pub mod lcm {'
	sed -e '0,/^\/\/ SPDX-License-Identifier/{/^\/\/ SPDX-License-Identifier/d}' \
	    -e '/^\/\/!/d' "$lcm"
	echo '    }'
	echo '}'
	echo
	echo '#[no_mangle]'
	echo 'pub extern "C" fn rs_gcd(a: usize, b: usize) -> usize {'
	echo '    algo::gcd::gcd(a, b)'
	echo '}'
	echo
	echo '#[no_mangle]'
	echo 'pub extern "C" fn rs_int_sqrt(x: usize) -> usize {'
	echo '    algo::int_sqrt::int_sqrt(x)'
	echo '}'
	echo
	echo '#[no_mangle]'
	echo 'pub extern "C" fn rs_lcm(a: usize, b: usize) -> usize {'
	echo '    algo::lcm::lcm(a, b)'
	echo '}'
	echo
	echo '#[no_mangle]'
	echo 'pub extern "C" fn rs_lcm_not_zero(a: usize, b: usize) -> usize {'
	echo '    algo::lcm::lcm_not_zero(a, b)'
	echo '}'
} > math_rs.rs

echo "math_rs.rs generated from:"
echo "  $isqrt"
echo "  $lcm"
