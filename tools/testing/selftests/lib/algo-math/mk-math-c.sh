# Generate math_c_orig.c: the C reference for the differential test, assembled
# from the kernel sources themselves rather than retyped, so it cannot drift
# away from what is being replaced.
#
# Transitional: goes away with the C halves of lib/math/{gcd,lcm,int_sqrt}.c.

set -e

top=$(git rev-parse --show-toplevel 2>/dev/null || echo ../../../../../..)
gcd_c=$top/lib/math/gcd.c
lcm_c=$top/lib/math/lcm.c
isqrt_c=$top/lib/math/int_sqrt.c

for f in "$gcd_c" "$lcm_c" "$isqrt_c"; do
	[ -r "$f" ] || { echo "$f: not found" >&2; exit 1; }
done

# Extract one function definition: from the line matching the signature up to
# the first line that is exactly "}" (kernel style puts the closing brace of a
# top-level function in column 0).
extract()
{
	awk -v pat="$1" '
		$0 ~ pat { inside = 1 }
		inside    { print }
		inside && $0 == "}" { exit }
	' "$2"
}

{
	tag='SPDX-'
	tag="${tag}License-Identifier: GPL-2.0"
	printf '// %s\n' "$tag"
	echo '//'
	echo '// GENERATED by mk-math-c.sh from lib/math/gcd.c, lib/math/lcm.c and'
	echo '// lib/math/int_sqrt.c. Do not edit; rerun the script instead.'
	echo
	echo '#include <stdint.h>'
	echo
	echo 'typedef unsigned long ulong;'
	echo
	echo '#define __ffs(x) __builtin_ctzl(x)'
	echo '#define __fls(x) ((int)(sizeof(long) * 8 - 1 - __builtin_clzl(x)))'
	echo '#define swap(a, b) do { ulong __t = (a); (a) = (b); (b) = __t; } while (0)'
	echo '#define static_branch_likely(x) (1)'
	echo
	extract '^static unsigned long binary_gcd[(]' "$gcd_c"
	echo
	extract '^unsigned long gcd[(]' "$gcd_c"
	echo
	extract '^unsigned long lcm[(]' "$lcm_c"
	echo
	extract '^unsigned long lcm_not_zero[(]' "$lcm_c"
	echo
	extract '^unsigned long int_sqrt[(]' "$isqrt_c"
} > math_c_orig.c

echo "math_c_orig.c generated from:"
echo "  $gcd_c"
echo "  $lcm_c"
echo "  $isqrt_c"
